mod_results_ui <- function(id) {
  ns <- NS(id)

  tagList(
    fluidRow(
      column(12,
        box(
          title = tagList(icon("info-circle"), "Quick Guide: Exploring Results"),
          status = "info", solidHeader = FALSE, width = 12,
          collapsible = TRUE, collapsed = TRUE,
          tags$div(
            style = "line-height: 1.6;",
            tags$p("This tab displays the outputs generated by the SalmonFlow pipeline:"),
            tags$ul(
              tags$li(tags$strong("Count Matrix:"), " A table of normalized gene expression values across all samples, summarized by tximport. Downloadable as CSV or TSV."),
              tags$li(tags$strong("Salmon QC:"), " A summary of quantification statistics, including the total number of processed reads, mapped reads, and mapping rates for each sample."),
              tags$li(tags$strong("MultiQC Report:"), " An interactive quality control report summarizing metrics from FastQC, fastp, and Salmon. Opens in a new tab.")
            )
          )
        )
      )
    ),

    fluidRow(
      column(12,
        box(
          title = tagList("Count Matrix (lengthScaledTPM)", html_tooltip("Table of gene expression values normalized using the selected tximport method.")),
          status = "primary", solidHeader = FALSE, width = 12,
          collapsible = TRUE,

          DTOutput(ns("count_table")),

          br(),

          fluidRow(
            column(3,
              downloadButton(ns("download_csv"), "Download CSV",
                             class = "btn-success")
            ),
            column(3,
              downloadButton(ns("download_tsv"), "Download TSV",
                             class = "btn-success")
            )
          )
        )
      )
    ),

    fluidRow(
      column(12,
        box(
          title = tagList("Downstream Analysis — iDEP", html_tooltip("Export the count matrix in the format expected by iDEP, then open your local iDEP instance to run differential expression and pathway analysis.")),
          status = "primary", solidHeader = FALSE, width = 12,
          collapsible = TRUE,

          tags$p(
            style = "line-height: 1.6;",
            "SalmonFlow's count matrix can be analysed directly in ",
            tags$a(href = "https://github.com/gexijin/idepGolem",
                   target = "_blank", rel = "noopener", "iDEP"),
            " for differential expression (DESeq2, limma, edgeR), clustering, PCA and pathway enrichment. ",
            "The exports below adapt the matrix to what iDEP expects: Ensembl version suffixes are removed so gene IDs map cleanly, ",
            "and values are rounded to whole counts."
          ),

          tags$ol(
            style = "line-height: 1.6;",
            tags$li("Download both files below."),
            tags$li("Click ", tags$strong("Open iDEP"), " — it opens in a new browser tab."),
            tags$li("In iDEP's ", tags$strong("Load Data"), " tab, upload the count matrix, then the design file.")
          ),

          br(),

          fluidRow(
            column(8, uiOutput(ns("idep_exports"))),
            column(4, uiOutput(ns("idep_link")))
          ),

          br(),
          uiOutput(ns("idep_status")),

          tags$p(
            style = "color:#5a6373; font-size:11px; margin-top:10px;",
            "iDEP is developed by the Ge lab at South Dakota State University and is free for non-commercial use (CC BY-NC 3.0). ",
            tags$a(href = "https://doi.org/10.1186/s12859-018-2486-6",
                   target = "_blank", rel = "noopener", "Ge, Son & Yao (2018), BMC Bioinformatics.")
          )
        )
      )
    ),

    fluidRow(
      column(6,
        box(
          title = tagList("Salmon QC — Mapping Rates", html_tooltip("Summary of total processed reads, mapped reads, and percentage mapping rates for each sample.")),
          status = "primary", solidHeader = FALSE, width = 12,
          DTOutput(ns("salmon_qc_table"))
        )
      ),
      column(6,
        box(
          title = tagList("MultiQC Report", html_tooltip("Click to open the interactive MultiQC quality control report in a new tab.")),
          status = "primary", solidHeader = FALSE, width = 12,
          uiOutput(ns("multiqc_link")),
          helpText("The MultiQC report will open in a new browser tab."),
          br(),
          uiOutput(ns("run_summary_download"))
        )
      )
    ),

    if (FALSE) {
      fluidRow(
        column(6,
          box(
            title = "PCA — Top Variable Genes",
            status = "primary", solidHeader = FALSE, width = 12,
            plotlyOutput(ns("pca_plot"), height = "450px")
          )
        ),
        column(6,
          box(
            title = "Heatmap — Top 50 Genes Más Variables",
            status = "primary", solidHeader = FALSE, width = 12,
            plotOutput(ns("heatmap_plot"), height = "500px")
          )
        )
      )
    }
  )
}

mod_results_server <- function(id, shared) {
  moduleServer(id, function(input, output, session) {
    ns <- session$ns

    # Host port the local iDEP container is published on. Read once at
    # startup — it is set by docker-compose, not changed at runtime.
    idep_port <- Sys.getenv("IDEP_PORT", "3839")

    # ── Count matrix table ─────────────────────────────────
    output$count_table <- renderDT({
      cm <- shared$count_matrix
      if (is.null(cm)) return(NULL)

      datatable(cm,
        filter   = "top",
        rownames = FALSE,
        options  = list(
          pageLength = 25,
          scrollX    = TRUE,
          dom        = "lfrtip",
          order      = list()
        )
      ) %>%
        formatRound(columns = setdiff(names(cm), "gene_id"), digits = 2)
    })

    # ── Downloads ──────────────────────────────────────────
    output$download_csv <- downloadHandler(
      filename = function() {
        paste0("salmonflow_counts_", format(Sys.time(), "%Y%m%d_%H%M"), ".csv")
      },
      content = function(file) {
        write.csv(shared$count_matrix, file, row.names = FALSE)
      }
    )

    output$download_tsv <- downloadHandler(
      filename = function() {
        paste0("salmonflow_counts_", format(Sys.time(), "%Y%m%d_%H%M"), ".tsv")
      },
      content = function(file) {
        write.table(shared$count_matrix, file, sep = "\t", row.names = FALSE, quote = FALSE)
      }
    )

    # ── iDEP exports ───────────────────────────────────────
    # Only offer the buttons once a run has produced a matrix, so a
    # click can never hand the browser an empty file.
    output$idep_exports <- renderUI({
      if (is.null(shared$count_matrix)) {
        return(tags$p(style = "color:#5a6373;",
                      "Run the pipeline to enable the iDEP exports."))
      }
      tagList(
        downloadButton(ns("download_idep_counts"), "Download iDEP Count Matrix",
                       class = "btn-success"),
        downloadButton(ns("download_idep_design"), "Download iDEP Design File",
                       class = "btn-success", style = "margin-left:8px;")
      )
    })

    output$download_idep_counts <- downloadHandler(
      filename = function() {
        paste0("salmonflow_idep_counts_", format(Sys.time(), "%Y%m%d_%H%M"), ".csv")
      },
      content = function(file) {
        idep_counts <- prepare_idep_counts(shared$count_matrix)

        if (is.null(idep_counts)) {
          showNotification("No count matrix available yet — run the pipeline first.",
                           type = "error")
          return(NULL)
        }

        merged <- attr(idep_counts, "merged_ids") %||% 0
        if (merged > 0) {
          showNotification(
            paste0("Removing Ensembl version suffixes collapsed ", merged,
                   " duplicate gene ID(s); their counts were summed."),
            type = "warning", duration = 10
          )
        }

        write.csv(idep_counts, file, row.names = FALSE)
      }
    )

    output$download_idep_design <- downloadHandler(
      filename = function() {
        paste0("salmonflow_idep_design_", format(Sys.time(), "%Y%m%d_%H%M"), ".csv")
      },
      content = function(file) {
        design <- build_idep_design(shared$samples)

        if (is.null(design)) {
          showNotification("No samples loaded — nothing to export.", type = "error")
          return(NULL)
        }

        if (!isTRUE(attr(design, "has_groups"))) {
          showNotification(
            paste("No groups were assigned in the Samples tab, so every sample is",
                  "labelled 'Ungrouped'. Fill in the group column and re-export,",
                  "or assign groups manually in iDEP."),
            type = "warning", duration = 12
          )
        }

        write.csv(design, file, row.names = FALSE)
      }
    )

    # ── Open iDEP ──────────────────────────────────────────
    # The href is built in the browser: this R process reaches iDEP at
    # idep:3838 on the compose network, but the user's browser needs
    # <same host as SalmonFlow>:3839. Deriving it from location.hostname
    # works both on a laptop and on a lab server accessed by IP.
    output$idep_link <- renderUI({
      tags$a(
        href = "#", class = "btn btn-primary",
        onclick = sprintf(
          "window.open(location.protocol + '//' + location.hostname + ':%s', '_blank', 'noopener'); return false;",
          idep_port
        ),
        icon("external-link-alt"), " Open iDEP"
      )
    })

    output$idep_status <- renderUI({
      if (idep_reachable()) {
        tags$p(style = "color:#66bb6a; font-size:12px;",
               icon("check-circle"),
               sprintf(" Local iDEP is running on port %s.", idep_port))
      } else {
        tags$p(style = "color:#5a6373; font-size:12px;",
               icon("exclamation-triangle"),
               " Could not reach a local iDEP instance. Start it with ",
               tags$code("docker compose up -d idep"),
               " (the first run downloads a large image). The button above still works if iDEP is running elsewhere.")
      }
    })

    # ── Salmon QC summary table ────────────────────────────
    output$salmon_qc_table <- renderDT({
      meta <- shared$salmon_meta
      if (is.null(meta) || length(meta) == 0) return(NULL)

      qc_df <- data.frame(
        Sample          = names(meta),
        Reads_Processed = sapply(meta, function(m) m$num_processed %||% NA),
        Reads_Mapped    = sapply(meta, function(m) m$num_mapped %||% NA),
        Mapping_Rate    = sapply(meta, function(m) {
          if (!is.na(m$percent_mapped)) paste0(m$percent_mapped, "%") else "N/A"
        }),
        stringsAsFactors = FALSE
      )

      datatable(qc_df, rownames = FALSE,
        options = list(dom = "t", pageLength = 50, scrollX = TRUE)) %>%
        formatStyle("Mapping_Rate",
          color = styleInterval(c(50), c("#ef5350", "#66bb6a")),
          fontWeight = "bold")
    })

    # ── MultiQC link ───────────────────────────────────────
    output$multiqc_link <- renderUI({
      pre  <- shared$multiqc_pre_report
      post <- shared$multiqc_post_report
      uni  <- shared$multiqc_report

      has_pre  <- !is.null(pre)  && nchar(pre)  > 0 && file.exists(pre)
      has_post <- !is.null(post) && nchar(post) > 0 && file.exists(post)
      has_uni  <- !is.null(uni)  && nchar(uni)  > 0 && file.exists(uni)

      if (has_pre && has_post) {
        addResourcePath("multiqc_pre",  dirname(pre))
        addResourcePath("multiqc_post", dirname(post))
        tagList(
          tags$a(href = paste0("multiqc_pre/",  basename(pre)),
                 target = "_blank", class = "btn btn-primary",
                 style = "margin-right:8px;",
                 icon("external-link-alt"), " MultiQC Pre-Trimming"),
          tags$a(href = paste0("multiqc_post/", basename(post)),
                 target = "_blank", class = "btn btn-success",
                 icon("external-link-alt"), " MultiQC Post-Trimming")
        )
      } else if (has_uni) {
        addResourcePath("multiqc", dirname(uni))
        tags$a(href = paste0("multiqc/", basename(uni)),
               target = "_blank",
               class = "btn btn-primary",
               icon("external-link-alt"),
               " Open MultiQC Report")
      } else {
        tags$p(style = "color:#5a6373;", "No MultiQC report available yet.")
      }
    })

    # ── Run summary log download ───────────────────────────
    output$run_summary_download <- renderUI({
      path <- shared$run_summary
      if (is.null(path) || nchar(path) == 0 || !file.exists(path)) return(NULL)
      downloadButton(ns("download_summary"), "Download Run Summary Log",
                     class = "btn-info")
    })

    output$download_summary <- downloadHandler(
      filename = function() {
        paste0("salmonflow_run_summary_", format(Sys.time(), "%Y%m%d_%H%M"), ".log")
      },
      content = function(file) {
        file.copy(shared$run_summary, file, overwrite = TRUE)
      }
    )

    # ── PCA Plot ───────────────────────────────────────────
    output$pca_plot <- renderPlotly({
      cm <- shared$count_matrix
      samples <- shared$samples
      if (is.null(cm) || is.null(samples)) return(NULL)

      # Prepare numeric matrix (exclude gene_id)
      mat <- cm[, setdiff(names(cm), "gene_id"), drop = FALSE]
      mat <- as.matrix(mat)
      mat[is.na(mat)] <- 0

      # Log2 transform
      mat_log <- log2(mat + 1)

      # Keep top 500 most variable genes
      gene_vars <- apply(mat_log, 1, var)
      top_idx   <- head(order(gene_vars, decreasing = TRUE), 500)
      mat_top   <- mat_log[top_idx, , drop = FALSE]

      # PCA
      pca <- prcomp(t(mat_top), center = TRUE, scale. = TRUE)
      pca_df <- data.frame(
        PC1    = pca$x[, 1],
        PC2    = pca$x[, 2],
        Sample = colnames(mat_top),
        stringsAsFactors = FALSE
      )

      # Add group info
      if (!is.null(samples$group) && any(samples$group != "")) {
        grp_map <- setNames(samples$group, samples$name)
        pca_df$Group <- grp_map[pca_df$Sample]
      } else {
        pca_df$Group <- "all"
      }

      # Variance explained
      var_pct <- round(pca$sdev^2 / sum(pca$sdev^2) * 100, 1)

      p <- ggplot(pca_df, aes(x = PC1, y = PC2, color = Group, text = Sample)) +
        geom_point(size = 4, alpha = 0.85) +
        labs(
          x = paste0("PC1 (", var_pct[1], "%)"),
          y = paste0("PC2 (", var_pct[2], "%)"),
          title = "PCA — Top 500 Variable Genes"
        ) +
        theme_minimal(base_size = 13) +
        theme(
          plot.background  = element_rect(fill = "#ffffff", color = NA),
          panel.background = element_rect(fill = "#ffffff", color = NA),
          panel.grid       = element_line(color = "#e0e4ec"),
          text             = element_text(color = "#1f2430"),
          axis.text        = element_text(color = "#5a6373"),
          legend.background = element_rect(fill = "#ffffff"),
          legend.text       = element_text(color = "#1f2430")
        ) +
        scale_color_brewer(palette = "Set2")

      ggplotly(p, tooltip = c("text", "Group")) %>%
        layout(
          paper_bgcolor = "#ffffff",
          plot_bgcolor  = "#ffffff",
          font = list(color = "#1f2430")
        )
    })

    # ── Heatmap ────────────────────────────────────────────
    output$heatmap_plot <- renderPlot({
      cm <- shared$count_matrix
      samples <- shared$samples
      if (is.null(cm)) return(NULL)

      # Prepare numeric matrix
      mat <- cm[, setdiff(names(cm), "gene_id"), drop = FALSE]
      rownames(mat) <- cm$gene_id
      mat <- as.matrix(mat)
      mat[is.na(mat)] <- 0

      # Log2 transform
      mat_log <- log2(mat + 1)

      # Top 50 most variable genes
      gene_vars <- apply(mat_log, 1, var)
      top_idx   <- head(order(gene_vars, decreasing = TRUE), 50)
      mat_top   <- mat_log[top_idx, , drop = FALSE]

      # Annotation
      ann_col <- NULL
      if (!is.null(samples) && !is.null(samples$group) && any(samples$group != "")) {
        ann_col <- data.frame(
          Group = samples$group,
          row.names = samples$name
        )
      }

      pheatmap(mat_top,
        color          = colorRampPalette(c("#0277bd", "#ffffff", "#ef6c00"))(100),
        border_color   = NA,
        fontsize_row   = 7,
        fontsize_col   = 10,
        annotation_col = ann_col,
        main           = "Top 50 — Most Variable Genes",
        clustering_method = "ward.D2"
      )
    }, bg = "#ffffff")
  })
}
